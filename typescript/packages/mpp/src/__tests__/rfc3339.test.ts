import { describe, expect, test } from 'vitest';

import { parseRfc3339 } from '../shared/rfc3339.js';

describe('parseRfc3339', () => {
    test.each([
        '2026-04-31T00:00:00Z',
        '2020-02-29',
        '1963-06-19',
        '23:59:60Z',
        '2026-01-29',
        '2026-02-30T00:00:00Z',
        '2026-01-29T24:00:00Z',
        '1990-02-31T15:59:59.123-08:00',
        '1990-12-31T24:00:00Z',
        '06/19/1963 08:30:06 PST',
        '1900-02-29T00:00:00Z',
        '2026-02-29T00:00:00Z',
        '2026-01-29T12:00:00',
        '2026-01-29T12:00:00+0000',
        '2026-01-29T12:00Z',
        '2026-09-31T00:00:00Z',
    ])('rejects non-RFC 3339 input %s', value => {
        expect(parseRfc3339(value)).toBeNaN();
    });

    test.each([
        ['1985-04-12t23:20:50.52z', '1985-04-12T23:20:50.520Z'],
        ['2021-09-29T16:04:33.0123456789Z', '2021-09-29T16:04:33.012Z'],
        ['1996-12-19T16:39:57-08:00', '1996-12-20T00:39:57.000Z'],
        ['2000-02-29T00:00:00+23:59', '2000-02-28T00:01:00.000Z'],
    ])('parses %s', (value, expected) => {
        expect(new Date(parseRfc3339(value)).toISOString()).toBe(expected);
    });
});

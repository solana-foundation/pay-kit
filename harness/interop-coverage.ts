// Which interop (client, server, scenario) cases does CI actually run?
//
// Replays the selection test/e2e.test.ts makes for every workflow step that
// runs it (adapter env selectors, MPP_HARNESS_INTENTS/SCENARIOS and the
// --testNamePattern filter), and for every shard of the generated charge
// matrix, then compares the union against every eligible case in the
// registry. The result is rendered into harness/README.md between markers
// and committed, so a workflow change that drops a case shows up in the PR
// diff even before interop claims move into harness/expectations/.
//
//   pnpm exec tsx interop-coverage.ts           # rewrite README.md
//   pnpm exec tsx interop-coverage.ts --check   # exit 1 if README.md is stale

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { enumerateChargeCases, planChargeMatrix } from "./src/ci-matrix";
import { testNamePattern, workflowRunSteps } from "./src/ci-workflows";
import {
  harnessScenarios,
  type HarnessScenario,
  selectHarnessScenarios,
} from "./src/contracts";
import {
  adapterSelector,
  clientImplementations,
  enabledUnder,
  type ImplementationDefinition,
  serverImplementations,
} from "./src/implementations";

const here = dirname(fileURLToPath(import.meta.url));
const README = join(here, "README.md");
const BEGIN = "<!-- interop:begin (generated by interop-coverage.ts; do not edit) -->";
const END = "<!-- interop:end -->";
const E2E = "test/e2e.test.ts";

type Case = { scenario: HarnessScenario; client: string; server: string };
const key = (c: { scenario: { id: string }; client: string; server: string }) =>
  `${c.scenario.id}|${c.client}|${c.server}`;

function supports(impl: ImplementationDefinition, scenario: HarnessScenario, role: "client" | "server") {
  const ids = role === "client" ? scenario.clientIds : scenario.serverIds;
  return (impl.intents ?? ["charge"]).includes(scenario.intent) && (!ids || ids.includes(impl.id));
}

// Standard pair-iterated scenarios only; portability and resubmit kinds are
// charge-only and fully enumerated by the charge matrix.
function pairScenario(s: HarnessScenario): boolean {
  return !s.kind || s.kind === "standard";
}

function cases(
  scenarios: readonly HarnessScenario[],
  clients: readonly ImplementationDefinition[],
  servers: readonly ImplementationDefinition[],
): Case[] {
  const out: Case[] = [];
  for (const scenario of scenarios.filter(pairScenario)) {
    for (const server of servers.filter((s) => supports(s, scenario, "server"))) {
      for (const client of clients.filter((c) => supports(c, scenario, "client"))) {
        out.push({ scenario, client: client.id, server: server.id });
      }
    }
  }
  return out;
}

// Cases one workflow step running e2e.test.ts executes.
function casesForEnv(env: Record<string, string | undefined>, pattern: string | undefined): Case[] {
  let scenarios: HarnessScenario[];
  try {
    scenarios = selectHarnessScenarios(env.MPP_HARNESS_INTENTS, env.MPP_HARNESS_SCENARIOS);
  } catch {
    return [];
  }
  const on = (role: "client" | "server") => (impl: ImplementationDefinition) =>
    enabledUnder(impl.id, adapterSelector(role, impl.id), env);
  const regex = pattern ? new RegExp(pattern) : undefined;
  return cases(scenarios, clientImplementations.filter(on("client")), serverImplementations.filter(on("server")))
    .filter((c) => !regex || regex.test(`mpp harness ${c.scenario.id}: ${c.client} client pays ${c.server} server`));
}

export function executedInterop(): { executed: Map<string, string[]>; eligible: Case[] } {
  const executed = new Map<string, string[]>();
  const add = (c: Case, origin: string) => executed.set(key(c), [...(executed.get(key(c)) ?? []), origin]);
  for (const step of workflowRunSteps()) {
    if (!step.run.includes(E2E)) continue;
    for (const c of casesForEnv(step.env, testNamePattern(step.run))) add(c, step.origin);
  }
  // mpp-matrix.yml runs every planned shard with `env: ${{ matrix.env }}`.
  for (const shard of planChargeMatrix()) {
    for (const c of casesForEnv(shard.env, undefined)) add(c, `mpp-matrix.yml#${shard.id}`);
  }
  return { executed, eligible: cases(harnessScenarios, clientImplementations, serverImplementations) };
}

// Harness test files no workflow step runs. A bare `vitest run` with no
// file argument runs every file, so such a step covers everything.
export function testFilesNeverRun(): string[] {
  const files = readdirSync(join(here, "test")).filter((f) => f.endsWith(".test.ts"));
  const runs = workflowRunSteps().filter((s) => /vitest run/.test(s.run) || /pnpm test:onchain/.test(s.run));
  return files
    .map((f) => `test/${f}`)
    .filter((f) => f !== "test/onchain.e2e.test.ts" || !runs.some((s) => /test:onchain/.test(s.run)))
    .filter((f) => !runs.some((s) => s.run.includes(f) || /vitest run\s*$/.test(s.run.trim())))
    .filter((f) => f !== "test/onchain.e2e.test.ts")
    .sort();
}

export function renderInteropTable(): string {
  const { executed, eligible } = executedInterop();
  const lines: string[] = [];
  const intents = [...new Set(eligible.map((c) => c.scenario.intent))].sort();
  lines.push("| Intent | Eligible cases | Run in CI | Never run |");
  lines.push("| --- | ---: | ---: | ---: |");
  for (const intent of intents) {
    const inIntent = eligible.filter((c) => c.scenario.intent === intent);
    const ran = inIntent.filter((c) => executed.has(key(c))).length;
    lines.push(`| ${intent} | ${inIntent.length} | ${ran} | ${inIntent.length - ran} |`);
  }
  lines.push("");
  for (const intent of intents.filter((i) => i !== "charge")) {
    const inIntent = eligible.filter((c) => c.scenario.intent === intent);
    const clients = [...new Set(inIntent.map((c) => c.client))].sort();
    const servers = [...new Set(inIntent.map((c) => c.server))].sort();
    lines.push(`**${intent}**: scenarios run in CI / eligible, per client (rows) and server (columns).`);
    lines.push("");
    lines.push(`| client \\ server | ${servers.join(" | ")} |`);
    lines.push(`| --- | ${servers.map(() => ":---:").join(" | ")} |`);
    for (const client of clients) {
      const cells = servers.map((server) => {
        const pair = inIntent.filter((c) => c.client === client && c.server === server);
        if (pair.length === 0) return "";
        const ran = pair.filter((c) => executed.has(key(c))).length;
        return ran === 0 ? `**0**/${pair.length}` : `${ran}/${pair.length}`;
      });
      lines.push(`| ${client} | ${cells.join(" | ")} |`);
    }
    lines.push("");
  }
  const never = testFilesNeverRun();
  lines.push(
    never.length === 0
      ? "Every harness test file is run by some CI step."
      : `Harness test files no CI step runs: ${never.map((f) => `\`${f}\``).join(", ")}.`,
  );
  return lines.join("\n");
}

function rewrite(readme: string, table: string): string {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) throw new Error(`README.md is missing ${BEGIN} / ${END}`);
  return `${readme.slice(0, start + BEGIN.length)}\n${table}\n${readme.slice(end)}`;
}

// Charge is enumerated over the full registry by the planner; assert the
// replay agrees, so the analyzer itself is checked against a known answer.
export function chargeReplayMatchesPlanner(): boolean {
  const { executed } = executedInterop();
  const planned = enumerateChargeCases(
    clientImplementations,
    serverImplementations,
    harnessScenarios.filter((s) => s.intent === "charge"),
  ).filter((c) => !c.targetServerId);
  return planned
    .filter((c) => pairScenario(harnessScenarios.find((s) => s.id === c.scenarioId)!))
    .every((c) => executed.has(`${c.scenarioId}|${c.clientId}|${c.serverId}`));
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const current = readFileSync(README, "utf8");
  const next = rewrite(current, renderInteropTable());
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("harness/README.md interop table is stale; run `pnpm interop` in harness/");
      process.exit(1);
    }
  } else {
    writeFileSync(README, next);
  }
}

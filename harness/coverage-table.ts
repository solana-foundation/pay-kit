// Render the conformance coverage table into harness/README.md.
//
// The table is generated from harness/expectations/*.toml and the case
// lists, not from run results: exact-set reconciliation guarantees that a
// green CI run observed exactly what the expectations declare, so the
// declared state IS the observed state whenever CI passes.
//
//   pnpm exec tsx coverage-table.ts           # rewrite README.md
//   pnpm exec tsx coverage-table.ts --check   # exit 1 if README.md is stale

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadVectors } from "./src/conformance/load";
import { type CaseRef, decide, loadAllExpectations } from "./src/expectations";
import { runnableFlowCases } from "./src/protocol/flow-driver";
import { collectProtocolCases } from "./src/protocol/vectors";

const here = dirname(fileURLToPath(import.meta.url));
const README = join(here, "README.md");
const BEGIN = "<!-- coverage:begin (generated by coverage-table.ts; do not edit) -->";
const END = "<!-- coverage:end -->";

export function renderCoverageTable(): string {
  const refs: CaseRef[] = [
    ...loadVectors().map((v) => ({ suite: "vector" as const, id: v.id, capability: v.intent })),
    ...collectProtocolCases().map((c) => ({
      suite: "protocol" as const,
      id: `${c.op} :: ${c.scenario}`,
      capability: "protocol",
    })),
    ...runnableFlowCases().map((c) => ({ suite: "flow" as const, id: c.name, capability: "flow" })),
  ];
  const expectations = loadAllExpectations();
  const languages = [...expectations.keys()].sort();
  const rows = [...new Set(refs.map((r) => `${r.suite}:${r.capability}`))].sort();

  const lines: string[] = [];
  lines.push(`| Suite | Cases | ${languages.join(" | ")} |`);
  lines.push(`| --- | ---: | ${languages.map(() => ":---:").join(" | ")} |`);
  for (const row of rows) {
    const inRow = refs.filter((r) => `${r.suite}:${r.capability}` === row);
    const label = row.endsWith(`:${row.split(":")[0]}`) ? row.split(":")[0] : row.replace(":", " ");
    const cells = languages.map((language) => {
      const exp = expectations.get(language)!;
      const counts = { pass: 0, unsupported: 0, known_failing: 0, unclaimed: 0 };
      for (const ref of inRow) counts[decide(exp, ref).kind] += 1;
      if (counts.unclaimed === inRow.length) return "—";
      const parts = [`${counts.pass}`];
      if (counts.unsupported) parts.push(`${counts.unsupported}u`);
      if (counts.known_failing) parts.push(`${counts.known_failing}k`);
      return parts.join(" · ");
    });
    lines.push(`| ${label} | ${inRow.length} | ${cells.join(" | ")} |`);
  }
  lines.push("");
  lines.push(
    "Each cell counts the cases that must pass, then `u` unsupported (declared, executed, must report unsupported) and `k` known failing (declared with tracking, executed, must fail). `—` means the SDK does not claim the suite. Source: `harness/expectations/<language>.toml`.",
  );
  return lines.join("\n");
}

function rewrite(readme: string, table: string): string {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`README.md is missing the ${BEGIN} / ${END} markers`);
  }
  return `${readme.slice(0, start + BEGIN.length)}\n${table}\n${readme.slice(end)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const current = readFileSync(README, "utf8");
  const next = rewrite(current, renderCoverageTable());
  if (process.argv.includes("--check")) {
    if (next !== current) {
      console.error("harness/README.md coverage table is stale; run `pnpm coverage` in harness/");
      process.exit(1);
    }
  } else {
    writeFileSync(README, next);
  }
}

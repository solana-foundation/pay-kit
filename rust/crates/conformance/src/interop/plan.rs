//! `pkc plan`: the conformance CI matrix, generated from the claims.
//!
//! One shard per SDK, run on every pull request as `Conformance / <sdk>`:
//! the SDK's offline suites (`pkc run --sdk <sdk> --tier offline`, the
//! vitest protocol and flow suites it claims) and its interop cases, all of
//! which pair it with the Rust reference (`cases::REFERENCE`): its client
//! against the Rust server and the Rust client against its server. The
//! `rust` shard runs Rust against Rust as the control. There are no pairs
//! between two other SDKs.
//!
//! `harness/interop-plan.json` and the README interop table are generated
//! from the same plan (`--write`) and checked for staleness (`--check`);
//! `harness/test/ci-coverage.test.ts` checks that harness.yml runs every
//! shard.

use std::collections::{BTreeMap, BTreeSet};

use serde::Serialize;
use serde_json::{json, Value};

use crate::run::expectations::{Expectations, Suite};

use super::cases::{self, Case, REFERENCE};
use super::claims::Intent;

pub const PLAN_FILE: &str = "harness/interop-plan.json";
const BEGIN: &str =
    "<!-- interop:begin (generated by `pkc plan --tier interop --write`; do not edit) -->";
const END: &str = "<!-- interop:end -->";

/// The offline suites a shard runs.
#[derive(Debug, Clone, Serialize)]
pub struct Offline {
    pub vector: bool,
    pub protocol: bool,
    pub flow: bool,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Shard {
    /// The SDK under test (`pkc run --sdk <id>`).
    pub id: String,
    pub runner: &'static str,
    /// Toolchains the job sets up (`adapters::TOOLCHAINS`); `rust` always,
    /// for `pkc` and the reference adapters.
    pub toolchains: Vec<&'static str>,
    /// Whether an `x402-upto` case needs the payment-channels program.
    pub needs_program: bool,
    pub offline: Offline,
    pub case_count: usize,
    /// Interop case keys.
    pub cases: Vec<String>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Plan {
    /// `capabilities.interop` per language, as parsed.
    pub claims: BTreeMap<String, Vec<String>>,
    /// Every claimed interop case key.
    pub cases: Vec<String>,
    pub shards: Vec<Shard>,
}

/// The shard owning a case: the SDK paired with the reference, or the
/// reference itself for the control.
pub fn owner(case: &Case) -> &'static str {
    if case.client.language != REFERENCE {
        case.client.language
    } else {
        case.server.language
    }
}

fn shard(id: &str, exp: &Expectations, cases: &[&Case]) -> Shard {
    let offline = Offline {
        vector: !exp.claims(Suite::Vector).is_empty(),
        protocol: !exp.claims(Suite::Protocol).is_empty(),
        flow: !exp.claims(Suite::Flow).is_empty(),
    };
    let mut toolchains: BTreeSet<&'static str> = [REFERENCE].into();
    if let Some(own) = super::adapters::TOOLCHAINS.iter().find(|t| **t == id) {
        toolchains.insert(own);
    }
    // The protocol and flow suites still run on vitest.
    if offline.protocol || offline.flow {
        toolchains.insert("typescript");
    }
    for c in cases {
        toolchains.insert(c.client.toolchain());
        toolchains.insert(c.server.toolchain());
    }
    let toolchains: Vec<&'static str> = super::adapters::TOOLCHAINS
        .iter()
        .copied()
        .filter(|t| toolchains.contains(t))
        .collect();
    let mut keys: Vec<String> = cases.iter().map(|c| c.key()).collect();
    keys.sort();
    Shard {
        id: id.to_string(),
        runner: if toolchains.contains(&"swift") {
            "macos-latest"
        } else {
            "ubuntu-latest"
        },
        needs_program: cases.iter().any(|c| c.scenario.needs_payment_channels()),
        offline,
        toolchains,
        case_count: keys.len(),
        cases: keys,
    }
}

pub fn plan(exps: &BTreeMap<String, Expectations>) -> Result<Plan, String> {
    let claimed = cases::claimed(exps)?;
    let mut by_sdk: BTreeMap<&str, Vec<&Case>> = BTreeMap::new();
    for case in &claimed {
        by_sdk.entry(owner(case)).or_default().push(case);
    }
    let mut shards = Vec::new();
    for (language, exp) in exps {
        let cases = by_sdk.remove(language.as_str()).unwrap_or_default();
        let s = shard(language, exp, &cases);
        if s.offline.vector || s.offline.protocol || s.offline.flow || !s.cases.is_empty() {
            shards.push(s);
        }
    }
    if let Some((sdk, _)) = by_sdk.into_iter().next() {
        return Err(format!(
            "interop cases owned by {sdk}, which has no harness/expectations/{sdk}.toml"
        ));
    }
    let mut keys: Vec<String> = claimed.iter().map(Case::key).collect();
    keys.sort();
    Ok(Plan {
        claims: exps
            .iter()
            .map(|(l, e)| {
                (
                    l.clone(),
                    e.claims(Suite::Interop).iter().cloned().collect(),
                )
            })
            .collect(),
        cases: keys,
        shards,
    })
}

impl Plan {
    pub fn find(&self, id: &str) -> Option<&Shard> {
        self.shards.iter().find(|s| s.id == id)
    }

    /// The GitHub matrix (case lists omitted; the job recomputes them from
    /// `--shard`).
    pub fn matrix(&self) -> Value {
        let include: Vec<Value> = self
            .shards
            .iter()
            .map(|s| {
                json!({
                    "sdk": s.id,
                    "runner": s.runner,
                    "toolchains": s.toolchains,
                    "needsProgram": s.needs_program,
                    "vector": s.offline.vector,
                    "protocol": s.offline.protocol,
                    "flow": s.offline.flow,
                    "interop": s.case_count > 0,
                    "caseCount": s.case_count,
                })
            })
            .collect();
        json!({ "include": include })
    }

    pub fn to_json(&self) -> String {
        format!(
            "{}\n",
            serde_json::to_string_pretty(self).expect("plan serialises")
        )
    }
}

/// The README interop table: per intent, claimed cases per client (rows)
/// and server (columns), with known-failing and unsupported counts from the
/// expectations files.
pub fn render(exps: &BTreeMap<String, Expectations>, plan: &Plan) -> Result<String, String> {
    let claimed = cases::claimed(exps)?;
    let mut decisions: BTreeMap<String, &'static str> = BTreeMap::new();
    for case in &claimed {
        decisions.insert(case.key(), cases::decide(exps, case)?.decision.kind());
    }
    let mut lines = vec![
        "| Intent | Claimed cases | Must pass | Known failing |".to_string(),
        "| --- | ---: | ---: | ---: |".to_string(),
    ];
    for intent in Intent::ALL {
        let mine: Vec<&Case> = claimed
            .iter()
            .filter(|c| c.scenario.intent == intent)
            .collect();
        if mine.is_empty() {
            continue;
        }
        let count = |kind: &str| mine.iter().filter(|c| decisions[&c.key()] == kind).count();
        lines.push(format!(
            "| {intent} | {} | {} | {} |",
            mine.len(),
            count("pass"),
            count("known_failing"),
        ));
    }
    lines.push(String::new());
    for intent in Intent::ALL {
        let mine: Vec<&Case> = claimed
            .iter()
            .filter(|c| c.scenario.intent == intent)
            .collect();
        if mine.is_empty() {
            continue;
        }
        lines.push(format!(
            "**{intent}**: claimed cases per SDK as client (against the Rust server) and as server (against the Rust client); `k` known failing."
        ));
        lines.push(String::new());
        lines.push("| SDK | as client | as server |".to_string());
        lines.push("| --- | :---: | :---: |".to_string());
        let sdks: BTreeSet<&str> = mine.iter().map(|c| owner(c)).collect();
        for sdk in sdks {
            let cell = |pick: &dyn Fn(&Case) -> bool| {
                let pair: Vec<&&Case> =
                    mine.iter().filter(|c| owner(c) == sdk && pick(c)).collect();
                if pair.is_empty() {
                    return String::new();
                }
                let k = pair
                    .iter()
                    .filter(|c| decisions[&c.key()] == "known_failing")
                    .count();
                if k > 0 {
                    format!("{} · {k}k", pair.len())
                } else {
                    pair.len().to_string()
                }
            };
            let (as_client, as_server) = if sdk == REFERENCE {
                (cell(&|_| true), "(control)".to_string())
            } else {
                (
                    cell(&|c| c.client.language == sdk),
                    cell(&|c| c.server.language == sdk),
                )
            };
            lines.push(format!("| {sdk} | {as_client} | {as_server} |"));
        }
        lines.push(String::new());
    }
    lines.push(format!(
        "{} SDK shards, each one `Conformance / <sdk>` job in `.github/workflows/conformance.yml` on every pull request. Source: `harness/expectations/<language>.toml` and the scenario registry in `rust/crates/conformance/src/interop/scenarios.rs`.",
        plan.shards.len()
    ));
    Ok(lines.join("\n"))
}

pub fn rewrite(readme: &str, table: &str) -> Result<String, String> {
    let start = readme
        .find(BEGIN)
        .ok_or_else(|| format!("harness/README.md is missing {BEGIN}"))?;
    let end = readme
        .find(END)
        .filter(|e| *e > start)
        .ok_or_else(|| format!("harness/README.md is missing {END}"))?;
    Ok(format!(
        "{}\n{table}\n{}",
        &readme[..start + BEGIN.len()],
        &readme[end..]
    ))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::interop::cases::all;

    fn find(id: &str) -> Case {
        all().into_iter().find(|c| c.id() == id).unwrap()
    }

    fn committed() -> BTreeMap<String, Expectations> {
        crate::run::expectations::load_all(&crate::repo_root().join("harness/expectations"))
            .unwrap()
    }

    #[test]
    fn every_case_pairs_an_sdk_with_the_reference() {
        for case in all() {
            assert!(case.languages().contains(REFERENCE), "{}", case.key());
        }
        assert_eq!(owner(&find("charge-basic/go/rust")), "go");
        assert_eq!(owner(&find("charge-basic/rust/php")), "php");
        assert_eq!(owner(&find("charge-basic/rust/rust")), "rust");
        assert!(all().iter().all(|c| c.id() != "charge-basic/go/php"));
    }

    #[test]
    fn every_claimed_case_is_in_exactly_one_shard() {
        let plan = plan(&committed()).unwrap();
        let mut seen = BTreeSet::new();
        for s in &plan.shards {
            for c in &s.cases {
                assert!(seen.insert(c.clone()), "{c} in two shards");
            }
        }
        assert_eq!(seen.len(), plan.cases.len());
    }

    #[test]
    fn only_swift_runs_on_macos_and_upto_shards_need_the_program() {
        let plan = plan(&committed()).unwrap();
        for s in &plan.shards {
            assert_eq!(s.runner == "macos-latest", s.id == "swift", "{}", s.id);
            assert_eq!(
                s.needs_program,
                s.cases.iter().any(|c| c.starts_with("interop/x402-upto-")),
                "{}",
                s.id
            );
        }
    }
}

//! `pkc report`: requirement x SDK traceability (DESIGN.md §3.4, PLAN phase 4).
//!
//! For every requirement mapped in `harness/requirements/{mpp,x402}.toml`:
//! the cases (vectors) that cite it and, per SDK, what the expectations
//! files say about each case (`pass`, `known_failing`, `unsupported`,
//! `unclaimed`). When `harness/results/<sdk>.json` exists, the observed
//! outcome of the last run is attached too. Next to it, the requirements
//! lint's gap list: unmapped normative sentences per spec file and section.
//!
//! Two outputs:
//!
//! - markdown between [`BEGIN`] / [`END`] in `harness/README.md`, built only
//!   from committed files (requirements, vectors, expectations, the pinned
//!   specs), so `--check` gives the same answer on every machine;
//! - `harness/results/report.json` (not committed): the same data plus the
//!   observed outcomes and the full unmapped sentence list.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use serde::Serialize;
use serde_json::Value;

use crate::case::SpecRepo;
use crate::reqlint::{self, RepoAnalysis};
use crate::run::expectations::{self, CaseRef, Expectations};
use crate::run::vectors::{self, Vector};

pub const BEGIN: &str = "<!-- traceability:begin (generated by `pkc report`; do not edit) -->";
pub const END: &str = "<!-- traceability:end -->";

/// One SDK's view of one case.
#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CaseStatus {
    /// `pass`, `known_failing`, `unsupported` or `unclaimed`, from
    /// `harness/expectations/<sdk>.toml`.
    pub expectation: &'static str,
    /// From `harness/results/<sdk>.json` when present: `pass`, `fail`,
    /// `unsupported`, or `not-run` (the results file predates the case or
    /// the SDK did not execute it).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub observed: Option<String>,
    /// The run's reconciliation verdict for the case, when observed.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub ok: Option<bool>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CaseRow {
    pub id: String,
    pub intent: String,
    pub mode: String,
    pub sdks: BTreeMap<String, CaseStatus>,
}

/// Per-SDK totals over a requirement's cases.
#[derive(Debug, Clone, Default, Serialize, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct Tally {
    pub pass: usize,
    pub known_failing: usize,
    pub unsupported: usize,
    pub unclaimed: usize,
}

impl Tally {
    fn add(&mut self, expectation: &str) {
        match expectation {
            "pass" => self.pass += 1,
            "known_failing" => self.known_failing += 1,
            "unsupported" => self.unsupported += 1,
            _ => self.unclaimed += 1,
        }
    }

    /// The coverage-table cell: passes, then `u` / `k`; `—` when the SDK
    /// claims none of the cases.
    pub fn cell(&self) -> String {
        if self.pass + self.known_failing + self.unsupported == 0 {
            return "—".into();
        }
        let mut out = self.pass.to_string();
        if self.unsupported > 0 {
            let _ = write!(out, " · {}u", self.unsupported);
        }
        if self.known_failing > 0 {
            let _ = write!(out, " · {}k", self.known_failing);
        }
        out
    }
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct RequirementRow {
    pub id: String,
    pub repo: &'static str,
    pub doc: String,
    pub section: String,
    pub text: String,
    pub required: bool,
    /// The mapped text no longer matches the pinned spec (req-lint fails).
    pub drifted: bool,
    pub cases: Vec<CaseRow>,
    pub sdks: BTreeMap<String, Tally>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SectionGap {
    pub section: String,
    pub normative: usize,
    pub mapped: usize,
    pub unmapped: usize,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct DocSummary {
    pub repo: &'static str,
    pub doc: String,
    pub normative: usize,
    pub mapped: usize,
    pub ignored: usize,
    pub unmapped: usize,
    pub sections: Vec<SectionGap>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Unmapped {
    pub id: String,
    pub repo: &'static str,
    pub doc: String,
    pub section: String,
    pub text: String,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Report {
    pub sdks: Vec<String>,
    pub docs: Vec<DocSummary>,
    pub requirements: Vec<RequirementRow>,
    pub unmapped: Vec<Unmapped>,
    /// Vectors that cite no requirement any requirements file maps.
    pub orphan_cases: Vec<String>,
}

/// `harness/results/<sdk>.json` cases keyed by case key.
type Observations = BTreeMap<String, BTreeMap<String, (String, bool)>>;

fn load_observations(results: &Path, sdks: &[String]) -> Observations {
    let mut out = Observations::new();
    for sdk in sdks {
        let Ok(text) = std::fs::read_to_string(results.join(format!("{sdk}.json"))) else {
            continue;
        };
        let Ok(json) = serde_json::from_str::<Value>(&text) else {
            continue;
        };
        let cases = out.entry(sdk.clone()).or_default();
        for c in json["cases"].as_array().into_iter().flatten() {
            let (Some(key), observed) = (c["key"].as_str(), c["observed"].as_str()) else {
                continue;
            };
            cases.insert(
                key.to_string(),
                (
                    observed.unwrap_or("not-run").to_string(),
                    c["ok"].as_bool().unwrap_or(false),
                ),
            );
        }
    }
    out
}

/// Assemble the report from already-loaded inputs (pure, for tests).
pub fn build(
    analyses: &[RepoAnalysis],
    vectors: &[Vector],
    expectations: &BTreeMap<String, Expectations>,
    observations: &Observations,
) -> Result<Report, String> {
    let sdks: Vec<String> = expectations.keys().cloned().collect();
    let mut by_req: BTreeMap<String, Vec<&Vector>> = BTreeMap::new();
    for v in vectors {
        for r in v.requirements() {
            by_req.entry(r).or_default().push(v);
        }
    }
    let mut mapped_ids = BTreeSet::new();
    let mut requirements = Vec::new();
    let mut docs = Vec::new();
    let mut unmapped = Vec::new();
    for analysis in analyses {
        let repo = analysis.repo.prefix();
        for req in &analysis.file.requirements {
            mapped_ids.insert(req.id.clone());
            let sentence = analysis.sentence_of(req);
            let mut cases = Vec::new();
            let mut tallies: BTreeMap<String, Tally> =
                sdks.iter().map(|s| (s.clone(), Tally::default())).collect();
            for v in by_req.get(&req.id).into_iter().flatten() {
                let case = CaseRef::vector(&v.id, &v.intent);
                let mut row = CaseRow {
                    id: v.id.clone(),
                    intent: v.intent.clone(),
                    mode: v.mode.clone(),
                    sdks: BTreeMap::new(),
                };
                for (sdk, exp) in expectations {
                    let expectation = exp.decide(&case)?.kind();
                    tallies.entry(sdk.clone()).or_default().add(expectation);
                    let seen = observations.get(sdk);
                    let (observed, ok) = match seen.and_then(|o| o.get(&case.key())) {
                        Some((observed, ok)) => (Some(observed.clone()), Some(*ok)),
                        None if seen.is_some() && expectation != "unclaimed" => {
                            (Some("not-run".to_string()), None)
                        }
                        None => (None, None),
                    };
                    row.sdks.insert(
                        sdk.clone(),
                        CaseStatus {
                            expectation,
                            observed,
                            ok,
                        },
                    );
                }
                cases.push(row);
            }
            requirements.push(RequirementRow {
                id: req.id.clone(),
                repo,
                doc: req.doc.clone(),
                section: sentence.map(|s| s.section.clone()).unwrap_or_default(),
                text: req.text.clone(),
                required: req.required,
                drifted: sentence.is_none(),
                cases,
                sdks: tallies,
            });
        }
        let gaps: BTreeSet<&str> = analysis.unmapped().iter().map(|s| s.id.as_str()).collect();
        for doc in &analysis.docs {
            let in_doc: Vec<_> = analysis
                .sentences
                .iter()
                .filter(|s| &s.doc == doc)
                .collect();
            let mut sections: Vec<SectionGap> = Vec::new();
            for s in &in_doc {
                let at = match sections.iter().position(|g| g.section == s.section) {
                    Some(at) => at,
                    None => {
                        sections.push(SectionGap {
                            section: s.section.clone(),
                            normative: 0,
                            mapped: 0,
                            unmapped: 0,
                        });
                        sections.len() - 1
                    }
                };
                let gap = &mut sections[at];
                gap.normative += 1;
                if gaps.contains(s.id.as_str()) {
                    gap.unmapped += 1;
                } else if !analysis.ignored(&s.id) {
                    gap.mapped += 1;
                }
            }
            docs.push(DocSummary {
                repo,
                doc: doc.clone(),
                normative: in_doc.len(),
                mapped: sections.iter().map(|g| g.mapped).sum(),
                ignored: in_doc.iter().filter(|s| analysis.ignored(&s.id)).count(),
                unmapped: sections.iter().map(|g| g.unmapped).sum(),
                sections,
            });
        }
        for s in analysis.unmapped() {
            unmapped.push(Unmapped {
                id: s.id.clone(),
                repo,
                doc: s.doc.clone(),
                section: s.section.clone(),
                text: s.text.clone(),
            });
        }
    }
    let orphan_cases = vectors
        .iter()
        .filter(|v| v.requirements().iter().all(|r| !mapped_ids.contains(r)))
        .map(|v| v.id.clone())
        .collect();
    Ok(Report {
        sdks,
        docs,
        requirements,
        unmapped,
        orphan_cases,
    })
}

pub fn load(root: &Path, vectors_dir: &Path, results: &Path) -> Result<Report, String> {
    let analyses: Vec<RepoAnalysis> = SpecRepo::ALL
        .into_iter()
        .map(|repo| reqlint::analyse(root, repo))
        .collect::<Result<_, _>>()?;
    let vectors = vectors::load(vectors_dir)?;
    let exp = expectations::load_all(&root.join("harness/expectations"))?;
    let sdks: Vec<String> = exp.keys().cloned().collect();
    let observations = load_observations(results, &sdks);
    build(&analyses, &vectors, &exp, &observations)
}

fn cell_text(text: &str) -> String {
    text.replace('|', "\\|")
}

fn short_doc(doc: &str) -> &str {
    doc.rsplit('/').next().unwrap_or(doc)
}

/// The README section. Uses only committed inputs: observed outcomes are
/// left out so the table does not depend on local results.
pub fn render(report: &Report) -> String {
    let mut out = String::new();
    let (mut mapped, mut unmapped, mut normative) = (0, 0, 0);
    for d in &report.docs {
        mapped += d.mapped;
        unmapped += d.unmapped;
        normative += d.normative;
    }
    let _ = writeln!(
        out,
        "{normative} normative sentences in the pinned specs: {mapped} mapped to a requirement, {unmapped} unmapped.\n"
    );
    let _ = writeln!(
        out,
        "| Spec file | Normative | Mapped | Ignored | Unmapped |\n| --- | ---: | ---: | ---: | ---: |"
    );
    for d in &report.docs {
        let _ = writeln!(
            out,
            "| `{}/{}` | {} | {} | {} | {} |",
            d.repo,
            short_doc(&d.doc),
            d.normative,
            d.mapped,
            d.ignored,
            d.unmapped
        );
    }

    let _ = writeln!(
        out,
        "\n**Requirements × SDK**: cases per requirement, and per SDK the cases it must pass, then `u` unsupported and `k` known failing; `—` means the SDK claims none of them. `*` marks `required = true` (req-lint fails if its last case goes).\n"
    );
    let _ = writeln!(
        out,
        "| Requirement | Spec § | Cases | {} |",
        report.sdks.join(" | ")
    );
    let _ = writeln!(
        out,
        "| --- | --- | ---: | {} |",
        report
            .sdks
            .iter()
            .map(|_| ":---:")
            .collect::<Vec<_>>()
            .join(" | ")
    );
    let mut rows: Vec<&RequirementRow> = report.requirements.iter().collect();
    rows.sort_by(|a, b| {
        (a.repo, &a.doc, &a.section, &a.id).cmp(&(b.repo, &b.doc, &b.section, &b.id))
    });
    for r in rows {
        let cells: Vec<String> = report
            .sdks
            .iter()
            .map(|s| r.sdks.get(s).map(Tally::cell).unwrap_or_default())
            .collect();
        let _ = writeln!(
            out,
            "| `{}`{}{} | {} § {} | {} | {} |",
            r.id,
            if r.required { "*" } else { "" },
            if r.drifted { " (text drifted)" } else { "" },
            short_doc(&r.doc),
            cell_text(&r.section),
            r.cases.len(),
            cells.join(" | ")
        );
    }

    let _ = writeln!(
        out,
        "\n<details><summary>Unmapped normative sentences by spec file and section ({unmapped})</summary>\n"
    );
    let _ = writeln!(
        out,
        "| Spec file | Section | Normative | Mapped | Unmapped |\n| --- | --- | ---: | ---: | ---: |"
    );
    for d in &report.docs {
        for s in d.sections.iter().filter(|s| s.unmapped > 0) {
            let section = if s.section.is_empty() {
                "(before the first heading)".to_string()
            } else {
                cell_text(&s.section)
            };
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} |",
                short_doc(&d.doc),
                section,
                s.normative,
                s.mapped,
                s.unmapped
            );
        }
    }
    out.push_str("\n</details>\n\n");
    out.push_str("Source: `harness/requirements/*.toml`, the vectors' `requirements`, `harness/expectations/<sdk>.toml`. Sentence texts and the observed outcome of the last local run per case are in `harness/results/report.json`; `pkc report --unmapped` prints the gap list.");
    if !report.orphan_cases.is_empty() {
        let _ = write!(
            out,
            "\n\nCases citing no mapped requirement: {}.",
            report
                .orphan_cases
                .iter()
                .map(|c| format!("`{c}`"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    out
}

pub fn rewrite(readme: &str, table: &str) -> Result<String, String> {
    let (Some(start), Some(end)) = (readme.find(BEGIN), readme.find(END)) else {
        return Err(format!(
            "harness/README.md is missing the {BEGIN} / {END} markers"
        ));
    };
    if end < start {
        return Err("traceability markers are out of order".into());
    }
    Ok(format!(
        "{}\n{table}\n{}",
        &readme[..start + BEGIN.len()],
        &readme[end..]
    ))
}

/// `pkc report [--check] [--unmapped [mpp|x402]]`.
pub fn command(root: &Path, check: bool, unmapped: Option<&str>) -> Result<(), String> {
    let results = root.join("harness/results");
    let report = load(root, &root.join("harness/vectors"), &results)?;
    if let Some(filter) = unmapped {
        for u in report
            .unmapped
            .iter()
            .filter(|u| filter.is_empty() || u.repo.starts_with(filter) || u.repo == filter)
        {
            println!("{}\t{} § {}\t{}", u.id, u.doc, u.section, u.text);
        }
        return Ok(());
    }
    std::fs::create_dir_all(&results).map_err(|e| e.to_string())?;
    std::fs::write(
        results.join("report.json"),
        format!(
            "{}\n",
            serde_json::to_string_pretty(&report).map_err(|e| e.to_string())?
        ),
    )
    .map_err(|e| e.to_string())?;
    let observed = report
        .requirements
        .iter()
        .flat_map(|r| &r.cases)
        .flat_map(|c| c.sdks.values())
        .filter(|s| s.ok == Some(false))
        .count();
    let unmapped_total: usize = report.docs.iter().map(|d| d.unmapped).sum();
    println!(
        "report: {} requirements ({} required), {} unmapped sentences, {} cases citing no mapped requirement; {} observed case results failed reconciliation; wrote harness/results/report.json",
        report.requirements.len(),
        report.requirements.iter().filter(|r| r.required).count(),
        unmapped_total,
        report.orphan_cases.len(),
        observed
    );
    for d in &report.docs {
        println!(
            "  {}/{}: {} normative, {} mapped, {} ignored, {} unmapped",
            d.repo, d.doc, d.normative, d.mapped, d.ignored, d.unmapped
        );
    }
    let readme_path = root.join("harness/README.md");
    let readme = std::fs::read_to_string(&readme_path).map_err(|e| e.to_string())?;
    let next = rewrite(&readme, &render(&report))?;
    if check {
        if next != readme {
            return Err("harness/README.md traceability table is stale; run `pkc report`".into());
        }
    } else if next != readme {
        std::fs::write(&readme_path, next).map_err(|e| e.to_string())?;
        println!("report: rewrote the traceability table in harness/README.md");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::reqlint::{Requirement, RequirementsFile, Sentence};
    use serde_json::json;

    fn analysis() -> RepoAnalysis {
        let repo = SpecRepo::MppSpecs;
        let mapped = "Servers MUST verify the amount.";
        let gap = "Servers MUST verify the | pipe.";
        let ignored = "Servers MUST be ignored.";
        let sentence = |text: &str, section: &str| Sentence {
            id: reqlint::sentence_id(repo, text),
            doc: "specs/d.md".into(),
            section: section.into(),
            text: text.into(),
        };
        RepoAnalysis {
            repo,
            file: RequirementsFile {
                repo: "mpp-specs".into(),
                commit: "c".into(),
                files: vec![],
                requirements: vec![Requirement {
                    id: reqlint::sentence_id(repo, mapped),
                    doc: "specs/d.md".into(),
                    text: mapped.into(),
                    required: true,
                }],
                ignores: vec![crate::reqlint::Ignore {
                    id: reqlint::sentence_id(repo, ignored),
                    reason: "n/a".into(),
                }],
            },
            docs: vec!["specs/d.md".into()],
            sentences: vec![
                sentence(mapped, "Verification"),
                sentence(gap, "Verification"),
                sentence(ignored, "Other"),
            ],
        }
    }

    fn vector(id: &str, req: &str) -> Vector {
        Vector {
            id: id.into(),
            intent: "charge".into(),
            mode: "verify-transaction".into(),
            file: "f.json".into(),
            raw: json!({ "id": id, "requirements": [req] }),
        }
    }

    fn exp(lang: &str, extra: &str) -> Expectations {
        Expectations::parse(
            &format!("language = \"{lang}\"\n[capabilities]\nvector = [\"charge\"]\nhonours_clock = true\n{extra}"),
            &format!("{lang}.toml"),
        )
        .unwrap()
    }

    #[test]
    fn tallies_expectations_and_attaches_observations() {
        let a = analysis();
        let req = a.file.requirements[0].id.clone();
        let vectors = vec![
            vector("c-1", &req),
            vector("c-2", &req),
            vector("c-3", "MPP-ffffffffff"),
        ];
        let exps: BTreeMap<String, Expectations> = [
            ("go".to_string(), exp("go", "[[known_failing]]\nid = \"vector/c-2\"\nreason = \"r\"\ntracking = \"FINDINGS.md#x\"\n")),
            ("lua".to_string(), Expectations::parse("language = \"lua\"\n", "lua.toml").unwrap()),
        ]
        .into();
        let mut observations = Observations::new();
        observations
            .entry("go".into())
            .or_default()
            .insert("vector/c-1".into(), ("pass".into(), true));
        let report = build(&[a], &vectors, &exps, &observations).unwrap();
        let row = &report.requirements[0];
        assert!(row.required && !row.drifted);
        assert_eq!(row.section, "Verification");
        assert_eq!(row.cases.len(), 2);
        assert_eq!(row.sdks["go"].cell(), "1 · 1k");
        assert_eq!(row.sdks["lua"].cell(), "—");
        let c1 = &row.cases[0].sdks["go"];
        assert_eq!((c1.observed.as_deref(), c1.ok), (Some("pass"), Some(true)));
        // go has a results file without c-2: not run. lua has none at all.
        assert_eq!(row.cases[1].sdks["go"].observed.as_deref(), Some("not-run"));
        assert_eq!(row.cases[1].sdks["lua"].observed, None);
        assert_eq!(report.orphan_cases, vec!["c-3"]);
        // One mapped, one unmapped, one ignored.
        let d = &report.docs[0];
        assert_eq!((d.normative, d.mapped, d.ignored, d.unmapped), (3, 1, 1, 1));
        assert_eq!(report.unmapped.len(), 1);

        let md = render(&report);
        assert!(md.contains("| `d.md` | Verification | 2 | 1 | 1 |"), "{md}");
        assert!(
            md.contains(&format!(
                "| `{req}`* | d.md § Verification | 2 | 1 · 1k | — |"
            )),
            "{md}"
        );
        // Observations never reach the committed table.
        let without = build(&[analysis()], &vectors, &exps, &Observations::new()).unwrap();
        assert_eq!(render(&without), md);
    }

    #[test]
    fn rewrite_replaces_only_between_markers() {
        let readme = format!("a\n{BEGIN}\nold\n{END}\nb");
        let next = rewrite(&readme, "new").unwrap();
        assert_eq!(next, format!("a\n{BEGIN}\nnew\n{END}\nb"));
        assert_eq!(rewrite(&next, "new").unwrap(), next);
        assert!(rewrite("no markers", "x").is_err());
    }
}

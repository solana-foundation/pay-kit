//! `pkc run --cross`: offline cross-verification (DESIGN.md §3.9). Every
//! SDK's saved builds (`harness/results/<sdk>/builds/<case>.json`, written by
//! `pkc run`) are fed to every server-capable SDK's `verify`. A cell agrees
//! when the server's verdict equals the Rust judge's verdict on that build
//! (accept a build Rust accepted, refuse one Rust refused). A disagreement is
//! either a server bug or a leniency Rust shares with the client.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use serde::Serialize;
use serde_json::json;

use crate::fixture_rpc::{Fixtures, HttpFixture};
use crate::run::driver::{Options, SavedBuild};
use crate::run::expectations::{self, CaseRef, Decision, Expectations, Suite};
use crate::run::judge;
use crate::run::testee::{Manifest, Testee};
use crate::run::vectors::{self, Vector};

pub const BEGIN: &str = "<!-- cross:begin (generated by `pkc run --cross`; do not edit) -->";
pub const END: &str = "<!-- cross:end -->";

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Cell {
    pub intent: String,
    pub client: String,
    pub server: String,
    pub case: String,
    /// The Rust judge's verdict on the build: `accept` or `reject`.
    pub expected: &'static str,
    /// The server's verdict: `accept`, `reject`, `unsupported` or `error`.
    pub observed: String,
    pub agree: bool,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
}

#[derive(Debug, Clone, Serialize)]
pub struct CrossReport {
    pub clients: Vec<String>,
    pub servers: BTreeMap<String, Vec<String>>,
    pub cells: Vec<Cell>,
}

/// SDKs whose expectations make them a verifier for `intent`: they claim it
/// and must pass (or are known to fail) at least one verify vector of it.
pub fn server_capable(exp: &Expectations, intent: &str, vectors: &[Vector]) -> bool {
    vectors
        .iter()
        .filter(|v| v.intent == intent && v.mode == "verify-transaction")
        .any(|v| {
            matches!(
                exp.decide(&CaseRef::vector(&v.id, &v.intent)),
                Ok(Decision::Pass | Decision::KnownFailing { .. })
            )
        })
}

pub fn load_builds(results: &Path) -> Result<Vec<SavedBuild>, String> {
    let mut builds = Vec::new();
    let Ok(dirs) = std::fs::read_dir(results) else {
        return Ok(builds);
    };
    let mut dirs: Vec<_> = dirs.flatten().map(|e| e.path()).collect();
    dirs.sort();
    for dir in dirs {
        let builds_dir = dir.join("builds");
        let Ok(files) = std::fs::read_dir(&builds_dir) else {
            continue;
        };
        let mut files: Vec<_> = files.flatten().map(|e| e.path()).collect();
        files.sort();
        for file in files {
            let text = std::fs::read_to_string(&file).map_err(|e| e.to_string())?;
            builds
                .push(serde_json::from_str(&text).map_err(|e| format!("{}: {e}", file.display()))?);
        }
    }
    Ok(builds)
}

pub fn cross(opts: &Options) -> Result<CrossReport, String> {
    let vectors = vectors::load(&opts.vectors_dir)?;
    let by_id: BTreeMap<&str, &Vector> = vectors.iter().map(|v| (v.id.as_str(), v)).collect();
    let all_exp = expectations::load_all(&opts.root.join("harness/expectations"))?;
    let manifests = Manifest::discover(&opts.root)?;
    let builds = load_builds(&opts.results_dir)?;
    if builds.is_empty() {
        return Err(format!(
            "no builds under {}/<sdk>/builds; run `pkc run --sdk <clients>` first",
            opts.results_dir.display()
        ));
    }
    let clients: BTreeSet<String> = builds.iter().map(|b| b.sdk.clone()).collect();
    // Sorted, so the table does not depend on the order of --sdk.
    let selected: BTreeSet<String> = if opts.sdks.is_empty() {
        manifests.iter().map(|m| m.language.clone()).collect()
    } else {
        opts.sdks.iter().cloned().collect()
    };
    let mut servers: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for intent in ["charge", "x402-exact"] {
        let list: Vec<String> = selected
            .iter()
            .filter(|sdk| {
                all_exp.get(*sdk).is_some_and(|e| {
                    e.claims(Suite::Cross).contains("cross")
                        && e.claims(Suite::Vector).contains(intent)
                        && server_capable(e, intent, &vectors)
                })
            })
            .cloned()
            .collect();
        servers.insert(intent.to_string(), list);
    }
    let server_sdks: BTreeSet<&String> = servers.values().flatten().collect();
    let cells = std::thread::scope(|scope| {
        let handles: Vec<_> = server_sdks
            .iter()
            .map(|server| {
                let manifest = manifests.iter().find(|m| &m.language == *server).cloned();
                let intents: Vec<&str> = servers
                    .iter()
                    .filter(|(_, list)| list.contains(server))
                    .map(|(i, _)| i.as_str())
                    .collect();
                let (builds, by_id) = (&builds, &by_id);
                scope.spawn(move || -> Vec<Cell> {
                    let Some(manifest) = manifest else {
                        let reason = format!("no runner manifest for {server}");
                        return builds
                            .iter()
                            .filter(|b| intents.contains(&b.intent.as_str()))
                            .filter(|b| by_id.contains_key(b.case.as_str()))
                            .map(|b| unstartable_cell(server, b, &reason))
                            .collect();
                    };
                    let mut testee = match Testee::new(
                        &manifest,
                        &opts.root,
                        opts.abi,
                        opts.prebuilt.as_deref(),
                        opts.timeout,
                        opts.startup_timeout,
                    ) {
                        Ok(t) => t,
                        Err(e) => {
                            // Every build this server should have verified
                            // becomes a failed cell, so a missing runner
                            // cannot look like a completed matrix.
                            let reason = format!("cannot start {server}: {e}");
                            eprintln!("cross: {reason}");
                            return builds
                                .iter()
                                .filter(|b| intents.contains(&b.intent.as_str()))
                                .filter(|b| by_id.contains_key(b.case.as_str()))
                                .map(|b| unstartable_cell(server, b, &reason))
                                .collect();
                        }
                    };
                    builds
                        .iter()
                        .filter(|b| intents.contains(&b.intent.as_str()))
                        .filter_map(|b| {
                            let vector = by_id.get(b.case.as_str())?;
                            Some(verify_one(&mut testee, server, b, vector))
                        })
                        .collect()
                })
            })
            .collect();
        handles
            .into_iter()
            .flat_map(|h| h.join().unwrap_or_default())
            .collect::<Vec<_>>()
    });
    let mut cells = cells;
    cells.sort_by(|a, b| {
        (&a.intent, &a.client, &a.server, &a.case).cmp(&(&b.intent, &b.client, &b.server, &b.case))
    });
    Ok(CrossReport {
        clients: clients.into_iter().collect(),
        servers,
        cells,
    })
}

fn unstartable_cell(server: &str, build: &SavedBuild, reason: &str) -> Cell {
    Cell {
        intent: build.intent.clone(),
        client: build.sdk.clone(),
        server: server.to_string(),
        case: build.case.clone(),
        expected: if build.judged { "accept" } else { "reject" },
        observed: "error".into(),
        agree: false,
        detail: Some(reason.to_string()),
    }
}

fn verify_one(testee: &mut Testee, server: &str, build: &SavedBuild, vector: &Vector) -> Cell {
    let expected = if build.judged { "accept" } else { "reject" };
    let mut cell = Cell {
        intent: build.intent.clone(),
        client: build.sdk.clone(),
        server: server.to_string(),
        case: build.case.clone(),
        expected,
        observed: "error".into(),
        agree: false,
        detail: None,
    };
    let input = match judge::verify_input_for_build(vector, &build.artifact) {
        Ok(i) => i,
        Err(e) => {
            cell.detail = Some(e);
            return cell;
        }
    };
    let rpc = match Fixtures::from_input(&input)
        .and_then(|f| HttpFixture::start(&f).map_err(|e| e.to_string()))
    {
        Ok(rpc) => rpc,
        Err(e) => {
            cell.detail = Some(e);
            return cell;
        }
    };
    let mut input = input;
    input["rpcUrl"] = json!(rpc.url());
    let id = format!("cross-{}-{}", build.sdk, build.case);
    let sent = json!({
        "id": id,
        "intent": build.intent,
        "mode": "verify-transaction",
        "description": format!("{} build of {}, verified by {server}", build.sdk, build.case),
        "input": input,
    });
    let exchange = testee.run("verify", &sent);
    match exchange.result {
        Err(e) => cell.detail = Some(e),
        Ok(result) => {
            let outcome = result["outcome"].as_str().unwrap_or_default();
            let error = result["error"].as_str().unwrap_or_default();
            cell.observed =
                if outcome == "unsupported-mode" || error.starts_with("unsupported-mode") {
                    "unsupported".into()
                } else {
                    outcome.to_string()
                };
            cell.agree = cell.observed == expected;
            if !cell.agree {
                cell.detail = Some(
                    format!(
                        "{} {}",
                        result["rejectCode"].as_str().unwrap_or_default(),
                        error
                    )
                    .trim()
                    .to_string(),
                );
            }
        }
    }
    cell
}

/// The README table: per intent, clients as rows, servers as columns,
/// `agreeing/total` per cell, bold when any build disagrees.
pub fn render(report: &CrossReport) -> String {
    let mut out = String::new();
    for (intent, servers) in &report.servers {
        let cells: Vec<&Cell> = report
            .cells
            .iter()
            .filter(|c| &c.intent == intent)
            .collect();
        if servers.is_empty() || cells.is_empty() {
            continue;
        }
        let clients: BTreeSet<&str> = cells.iter().map(|c| c.client.as_str()).collect();
        let _ = writeln!(
            out,
            "**{intent}**: builds by the client SDK (rows) verified by the server SDK (columns), agreeing with the Rust judge / total.\n"
        );
        let _ = writeln!(out, "| client \\ server | {} |", servers.join(" | "));
        let _ = writeln!(
            out,
            "| --- | {} |",
            servers
                .iter()
                .map(|_| ":---:")
                .collect::<Vec<_>>()
                .join(" | ")
        );
        for client in clients {
            let row: Vec<String> = servers
                .iter()
                .map(|server| {
                    let pair: Vec<&&Cell> = cells
                        .iter()
                        .filter(|c| c.client == client && &c.server == server)
                        .collect();
                    if pair.is_empty() {
                        return String::new();
                    }
                    // A server that declares it cannot express a build
                    // (e.g. a v2-only server given a v1 credential) is
                    // shown as `u`, not as a disagreement.
                    let unsupported = pair.iter().filter(|c| c.observed == "unsupported").count();
                    let judged = pair.len() - unsupported;
                    let agree = pair.iter().filter(|c| c.agree).count();
                    let mut cell = if agree == judged {
                        format!("{agree}/{judged}")
                    } else {
                        format!("**{agree}**/{judged}")
                    };
                    if unsupported > 0 {
                        cell.push_str(&format!(" · {unsupported}u"));
                    }
                    cell
                })
                .collect();
            let _ = writeln!(out, "| {client} | {} |", row.join(" | "));
        }
        out.push('\n');
    }
    out.push_str("A server agrees with a build when it accepts what the Rust judge accepted (verifier plus instruction multiset against the kit's own build) and refuses what it refused; `u` counts builds the server reports it cannot express. Disagreements are listed in `harness/results/cross.json`.");
    out
}

pub fn rewrite(readme: &str, table: &str) -> Result<String, String> {
    let (Some(start), Some(end)) = (readme.find(BEGIN), readme.find(END)) else {
        return Err(format!(
            "harness/README.md is missing the {BEGIN} / {END} markers"
        ));
    };
    if end < start {
        return Err("cross markers are out of order".into());
    }
    Ok(format!(
        "{}\n{table}\n{}",
        &readme[..start + BEGIN.len()],
        &readme[end..]
    ))
}

#[cfg(test)]
mod tests {
    #[test]
    fn an_unstartable_server_yields_failed_cells() {
        let build = crate::run::driver::SavedBuild {
            sdk: "rust".into(),
            case: "charge-sol-native-build".into(),
            intent: "charge".into(),
            artifact: String::new(),
            judged: true,
        };
        let cell = unstartable_cell("kotlin", &build, "cannot start kotlin: missing binary");
        assert!(!cell.agree);
        assert_eq!(cell.observed, "error");
        assert_eq!(cell.expected, "accept");
        assert_eq!(
            cell.detail.as_deref(),
            Some("cannot start kotlin: missing binary")
        );
    }

    use super::*;

    #[test]
    fn renders_and_bolds_disagreement() {
        let cell = |client: &str, server: &str, agree: bool| Cell {
            intent: "charge".into(),
            client: client.into(),
            server: server.into(),
            case: "c".into(),
            expected: "accept",
            observed: if agree {
                "accept".into()
            } else {
                "reject".into()
            },
            agree,
            detail: None,
        };
        let report = CrossReport {
            clients: vec!["a".into(), "b".into()],
            servers: [("charge".to_string(), vec!["s".to_string(), "t".to_string()])].into(),
            cells: vec![
                cell("a", "s", true),
                cell("a", "t", false),
                cell("b", "s", true),
            ],
        };
        let table = render(&report);
        assert!(table.contains("| a | 1/1 | **0**/1 |"), "{table}");
        assert!(table.contains("| b | 1/1 |  |"), "{table}");
        let readme = format!("x\n{BEGIN}\nold\n{END}\ny");
        let next = rewrite(&readme, &table).unwrap();
        assert!(next.contains("| a | 1/1"));
        assert!(!next.contains("old"));
        assert_eq!(rewrite(&next, &table).unwrap(), next);
    }
}
